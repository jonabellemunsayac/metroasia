const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../assets/js/open-play.js'), 'utf8');
const context = vm.createContext({});
vm.runInContext(source.match(/^function groupOpenPlayAdminSessions\([^]*?^}/m)[0], context);
const now = Date.parse('2026-10-10T14:00:00+08:00');
const row = {sessionId:1,date:'2026-10-10',startsAt:'09:00:00',endsAt:'12:00:00',seat:1,id:'openplay:1',status:'Booked'};
let groups = context.groupOpenPlayAdminSessions([row,{...row,id:'openplay:2',seat:2,status:'Held'}],now);
assert.equal(groups.length,1);
assert.equal(groups[0].players.length,2);
assert.equal(groups[0].completed,false);
assert.equal(groups[0].pending,1);
groups = context.groupOpenPlayAdminSessions([row,{...row,id:'openplay:2',seat:2,status:'Cancelled'}],now);
assert.equal(groups[0].completed,true);
assert.equal(context.groupOpenPlayAdminSessions([{...row,startsAt:'15:00:00',endsAt:'18:00:00'}],now)[0].completed,false);
assert.equal(context.groupOpenPlayAdminSessions([{...row,startsAt:'21:00:00',endsAt:'00:00:00'}],now)[0].completed,false);
assert.equal(context.groupOpenPlayAdminSessions([{...row,startsAt:'21:00:00',endsAt:'00:00:00'}],Date.parse('2026-10-11T00:01:00+08:00'))[0].completed,true);
assert.equal(context.groupOpenPlayAdminSessions([row,{...row,sessionId:2}],now).length,2);
assert.equal(row.status,'Booked');
console.log('Session grouping: pending review, confirmed future sessions, ended sessions, cancelled players and midnight boundaries passed without status changes.');
